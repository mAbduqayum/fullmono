package migrations_test

import (
	_ "embed"
	"slices"
	"testing"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/mAbduqayum/fullmono/apps/api/internal/pgtest"
)

// An integration test (see pgtest): schema.sql is written by hand, for reading,
// so this checks it still adds up to what the migrations build.

//go:embed schema.sql
var schemaSQL string

// The schema as Postgres's catalog sees it, one sorted line per table or
// sequence, column, constraint and index, so that two schemas compare as two
// lists. golang-migrate's own table, schema_migrations, isn't part of it.
const describeSchema = `
SELECT line FROM (
	SELECT format('%s %s', CASE relkind WHEN 'r' THEN 'table' WHEN 'S' THEN 'sequence'
		WHEN 'v' THEN 'view' ELSE 'relkind ' || relkind::text END, relname) AS line
	FROM pg_class
	WHERE relnamespace = 'public'::regnamespace AND relkind <> 'i'

	UNION ALL
	SELECT format('column %s.%s %s%s%s%s', c.relname, a.attname,
		format_type(a.atttypid, a.atttypmod),
		CASE WHEN a.attnotnull THEN ' not null' END,
		' default ' || pg_get_expr(d.adbin, d.adrelid),
		CASE a.attidentity WHEN 'a' THEN ' generated always as identity'
			WHEN 'd' THEN ' generated by default as identity' END)
	FROM pg_attribute a
	JOIN pg_class c ON c.oid = a.attrelid
	LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
	WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
		AND a.attnum > 0 AND NOT a.attisdropped

	UNION ALL
	SELECT format('constraint %s.%s %s', conrelid::regclass, conname, pg_get_constraintdef(oid))
	FROM pg_constraint
	WHERE connamespace = 'public'::regnamespace

	UNION ALL
	SELECT indexdef FROM pg_indexes WHERE schemaname = 'public'
) AS schema
WHERE line NOT LIKE '%schema_migrations%'
ORDER BY line`

func TestSchemaSQLMatchesTheMigrations(t *testing.T) {
	migrated := pgtest.Pool(t)
	written := pgtest.EmptyPool(t)
	// No arguments, so pgx sends it as one simple query: every statement runs.
	if _, err := written.Exec(t.Context(), schemaSQL); err != nil {
		t.Fatalf("schema.sql doesn't run: %v", err)
	}

	want, got := describe(t, migrated), describe(t, written)
	for _, line := range want {
		if !slices.Contains(got, line) {
			t.Errorf("the migrations have, schema.sql doesn't: %s", line)
		}
	}
	for _, line := range got {
		if !slices.Contains(want, line) {
			t.Errorf("schema.sql has, the migrations don't: %s", line)
		}
	}
}

func describe(t *testing.T, pool *pgxpool.Pool) []string {
	t.Helper()
	rows, err := pool.Query(t.Context(), describeSchema)
	if err != nil {
		t.Fatal(err)
	}
	lines, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		t.Fatal(err)
	}
	if len(lines) == 0 {
		t.Fatal("the schema has nothing in it")
	}
	return lines
}
